import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js'
import { WebStandardStreamableHTTPServerTransport } from '@modelcontextprotocol/sdk/server/webStandardStreamableHttp.js'
import { z } from 'zod'

import {
  MAX_SEARCH_LIMIT,
  getAgentSessionDetail,
  getAgentVenue,
  listSports,
  listVenues,
  searchSessions,
} from '@/data/agent.data.server'
import { roundTypes } from '@/data/sessions'
import { SITE_NAME, SITE_URL } from '@/lib/seo'

const INSTRUCTIONS = `The full session schedule for the 2028 Summer Games in Los Angeles (July 10-30, 2028), with an AI-written guide to each.

Every session has a score from 0 to 10: how worth attending it is, combining significance (medals on the line), experience (venue, time of day), star power, uniqueness and ticket demand. Scores, summaries and contenders are generated by Claude from web research and are opinions. This is an unofficial guide: verify details against official sources before buying tickets. Times are local Pacific time.

Typical flow: list_sports or list_venues to learn the exact names, search_sessions to shortlist, then get_session for the full writeup of the ones that matter. Link people to each session's url. Source: ${SITE_URL}`

const readOnly = { readOnlyHint: true, openWorldHint: false } as const

function json(value: unknown) {
  return { content: [{ type: 'text' as const, text: JSON.stringify(value) }] }
}

function notFound(message: string) {
  return { content: [{ type: 'text' as const, text: message }], isError: true }
}

const dayKey = z.string().regex(/^(\d{4}-)?\d{2}-\d{2}$/, 'Use YYYY-MM-DD, e.g. 2028-07-19')

// A new server per request: the endpoint is stateless, and McpServer holds per-connection state.
export function createMcpServer(): McpServer {
  const server = new McpServer(
    { name: '28games', title: SITE_NAME, version: '1.0.0', websiteUrl: SITE_URL },
    { instructions: INSTRUCTIONS },
  )

  server.registerTool(
    'search_sessions',
    {
      title: 'Search sessions',
      description:
        'Find sessions by sport, venue, zone, round, date range, minimum score or keyword. Returns compact summaries, best-scored first unless sort is "date". Page with offset/nextOffset.',
      inputSchema: {
        sport: z.string().optional().describe('Exact sport name from list_sports, e.g. "Swimming"'),
        venue: z.string().optional().describe('Exact venue name from list_venues'),
        zone: z.string().optional().describe('Area of LA or host city, e.g. "Inglewood", "DTLA"'),
        round: z.enum(roundTypes).optional().describe('Final includes gold medal sessions'),
        date_from: dayKey.optional().describe('First day to include, YYYY-MM-DD'),
        date_to: dayKey.optional().describe('Last day to include, YYYY-MM-DD'),
        min_score: z.number().min(0).max(10).optional().describe('Minimum 0-10 score'),
        text: z
          .string()
          .optional()
          .describe('Keyword matched against sport and event description, e.g. "100m"'),
        sort: z.enum(['score', 'date']).optional().describe('Default "score"'),
        limit: z.number().int().min(1).max(MAX_SEARCH_LIMIT).optional().describe('Default 20'),
        offset: z.number().int().min(0).optional(),
      },
      annotations: readOnly,
    },
    async (args) =>
      json(
        searchSessions({
          sport: args.sport,
          venue: args.venue,
          zone: args.zone,
          round: args.round,
          dateFrom: args.date_from,
          dateTo: args.date_to,
          minScore: args.min_score,
          text: args.text,
          sort: args.sort,
          limit: args.limit,
          offset: args.offset,
        }),
      ),
  )

  server.registerTool(
    'get_session',
    {
      title: 'Get session',
      description:
        'Full guide to one session: summary, score breakdown with reasons, athletes to watch, related news, sport context and venue facts.',
      inputSchema: { id: z.string().describe('Session id from search_sessions, e.g. "SWM05"') },
      annotations: readOnly,
    },
    async ({ id }) => {
      const detail = getAgentSessionDetail(id.trim().toUpperCase())
      return detail ? json(detail) : notFound(`No session with id "${id}". Use search_sessions.`)
    },
  )

  server.registerTool(
    'list_sports',
    {
      title: 'List sports',
      description:
        'Every sport with its session count, medal sessions, top score, venues and dates.',
      inputSchema: {},
      annotations: readOnly,
    },
    async () => json(listSports()),
  )

  server.registerTool(
    'list_venues',
    {
      title: 'List venues',
      description: 'Every venue with its zone, location, capacity, sports and dates.',
      inputSchema: {},
      annotations: readOnly,
    },
    async () => json(listVenues()),
  )

  server.registerTool(
    'get_venue',
    {
      title: 'Get venue',
      description:
        'One venue: history, spectator experience, changes for 2028 and its full session schedule.',
      inputSchema: { name: z.string().describe('Venue name from list_venues') },
      annotations: readOnly,
    },
    async ({ name }) => {
      const venue = getAgentVenue(name)
      return venue ? json(venue) : notFound(`No venue named "${name}". Use list_venues.`)
    },
  )

  return server
}

// The data is public, so any origin may call the endpoint, which browser-based MCP clients need.
const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, POST, DELETE, OPTIONS',
  'Access-Control-Allow-Headers':
    'Content-Type, Accept, Authorization, Mcp-Session-Id, Mcp-Protocol-Version, Last-Event-ID',
  'Access-Control-Expose-Headers': 'Mcp-Session-Id, Mcp-Protocol-Version',
}

// Stateless and read-only: each request gets a fresh server and transport and plain JSON
// responses, so nothing is shared between requests and any serverless instance can answer.
export async function handleMcpRequest(request: Request): Promise<Response> {
  if (request.method === 'OPTIONS') {
    return new Response(null, { status: 204, headers: CORS_HEADERS })
  }

  const transport = new WebStandardStreamableHTTPServerTransport({
    sessionIdGenerator: undefined,
    enableJsonResponse: true,
  })
  await createMcpServer().connect(transport)

  const response = await transport.handleRequest(request)
  const headers = new Headers(response.headers)
  for (const [name, value] of Object.entries(CORS_HEADERS)) headers.set(name, value)
  headers.set('Cache-Control', 'no-store')
  return new Response(response.body, { status: response.status, headers })
}
